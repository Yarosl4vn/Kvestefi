    private fun ph(topic: String, exam: String, difficulty: Int, question: String, options: List<String>, explanation: String) =
        build("phys", topic, exam, difficulty, question, options, explanation)

    private fun ch(topic: String, exam: String, difficulty: Int, question: String, options: List<String>, explanation: String) =
        build("chem", topic, exam, difficulty, question, options, explanation)

    private fun b(topic: String, exam: String, difficulty: Int, question: String, options: List<String>, explanation: String) =
        build("bio", topic, exam, difficulty, question, options, explanation)

    private fun g(topic: String, exam: String, difficulty: Int, question: String, options: List<String>, explanation: String) =
        build("geo", topic, exam, difficulty, question, options, explanation)

    private fun s(topic: String, exam: String, difficulty: Int, question: String, options: List<String>, explanation: String) =
        build("social", topic, exam, difficulty, question, options, explanation)

    private fun i(topic: String, exam: String, difficulty: Int, question: String, options: List<String>, explanation: String) =
        build("info", topic, exam, difficulty, question, options, explanation)

    private fun en(topic: String, exam: String, difficulty: Int, question: String, options: List<String>, explanation: String) =
        build("eng", topic, exam, difficulty, question, options, explanation)

    private fun l(topic: String, exam: String, difficulty: Int, question: String, options: List<String>, explanation: String) =
        build("lit", topic, exam, difficulty, question, options, explanation)

    private fun build(
        code: String,
        topic: String,
        exam: String,
        difficulty: Int,
        question: String,
        options: List<String>,
        explanation: String
    ) = Task(
        id = 0,
        subjectCode = code,
        topic = topic,
        exam = exam,
        difficulty = difficulty,
        question = question,
        options = options,
        correctIndex = 0,
        explanation = explanation
    )
}
